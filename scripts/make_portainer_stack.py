#!/usr/bin/env python3
"""Generates examples/portainer-stack.yml: a single compose file with the app embedded (base64 tar.gz),
for Portainer's "Web editor" (no build, no registry needed). Re-run after you change app.py or a locale file.

Usage: python3 scripts/make_portainer_stack.py
"""
import base64
import glob
import io
import os
import tarfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tar:
    for name in ["app.py"] + sorted(os.path.relpath(f, root) for f in glob.glob(os.path.join(root, "locales", "*.json"))):
        info = tar.gettarinfo(os.path.join(root, name), arcname=name)
        info.uid = info.gid = 0
        info.uname = info.gname = ""
        info.mtime = 0
        with open(os.path.join(root, name), "rb") as fh:
            tar.addfile(info, fh)
b64 = base64.b64encode(buf.getvalue()).decode()

TEMPLATE = """# LineRoulette as a Portainer stack: Stacks -> Add stack -> Web editor -> paste this file.
# Set the environment variables in the form below the editor (at least ADMIN_PASSWORD).
# Generated by scripts/make_portainer_stack.py - the application is embedded, nothing is built or downloaded except python:3.12-slim.
services:
  lineroulette:
    image: python:3.12-slim
    container_name: lineroulette
    restart: unless-stopped
    ports:
      - "${HTTP_PORT:-8080}:8080"
    environment:
      ADMIN_USER: "${ADMIN_USER:-admin}"
      ADMIN_PASSWORD: "${ADMIN_PASSWORD:?ADMIN_PASSWORD must be set (min. 10 characters)}"
      ADMIN_RESET: "${ADMIN_RESET:-0}"
      BASE_DOMAIN: "${BASE_DOMAIN:-}"
      ADMIN_HOST: "${ADMIN_HOST:-}"
      PUBLIC_SCHEME: "${PUBLIC_SCHEME:-https}"
      PUBLIC_URL: "${PUBLIC_URL:-}"
      TRUST_PROXY: "${TRUST_PROXY:-1}"
      SESSION_HOURS: "${SESSION_HOURS:-12}"
      DEFAULT_LANG: "${DEFAULT_LANG:-en}"
      CONTENT_LANG: "${CONTENT_LANG:-}"
      DATE_FORMAT: "${DATE_FORMAT:-%Y-%m-%d}"
      TIME_FORMAT: "${TIME_FORMAT:-%H:%M}"
      DB_PATH: /data/data.db
      PORT: "8080"
      PYTHONUNBUFFERED: "1"
      TZ: "${TZ:-UTC}"
    volumes:
      - lineroulette-data:/data
    command:
      - sh
      - -c
      - "mkdir -p /app && echo '@@B64@@' | base64 -d | tar -xz -C /app && exec python /app/app.py"
    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request;urllib.request.urlopen('http://127.0.0.1:8080/healthz')"]
      interval: 30s
      timeout: 5s
      retries: 3

volumes:
  lineroulette-data:
"""
out = os.path.join(root, "examples", "portainer-stack.yml")
with open(out, "w", encoding="utf-8") as fh:
    fh.write(TEMPLATE.replace("@@B64@@", b64))
print("written:", os.path.relpath(out, root), f"({len(b64)} base64 bytes)")
